<?php
declare(strict_types=1);
require __DIR__ . '/run.php';

$import = new \App\Services\StatementImportService($db, $tx, $cardService);
$income = array_values(array_filter($reports->categories(1), static fn(array $category): bool => $category['tipo'] === 'receita'))[0];
$rows = $import->parse('extrato.csv', "Data;Descrição;Valor\n10/04/2025;Café importado;-12,50\n11/04/2025;Receita importada;50,00\n");
check(count($rows) === 2 && $rows[0]['centavos'] === -1250 && $rows[1]['centavos'] === 5000, 'CSV preview and signed amounts');
$defaults = $import->applyDefaults($rows, 'pix', $a, null);
check(count(array_filter($defaults, static fn(array $row): bool => $row['destino_tipo'] === 'conta' && $row['conta_id'] === $a && $row['meio_pagamento'] === 'pix')) === 2, 'Top payment type applies to every row');
rejects(fn() => $import->applyDefaults($rows, 'cartao', $a, null), 'Card default requires a card');
$ofx = $import->parse('extrato.ofx', '<STMTTRN><DTPOSTED>20250412<TRNAMT>-7.25<NAME>Mercado OFX</STMTTRN>');
check(count($ofx) === 1 && $ofx[0]['data'] === '2025-04-12' && $ofx[0]['centavos'] === -725, 'OFX preview');
$batch = $import->import(1, $a, $rows, [0 => '1', 1 => '1'], [0 => $expense['id'], 1 => $income['id']]);
check((int) $import->lastBatch(1)['id'] === $batch, 'Import batch saved');
check($import->duplicate(1, $a, $rows[0]), 'Existing transaction detected');
rejects(fn() => $import->import(2, $foreign, [$rows[0]], [0 => '1'], [0 => $expense['id']]), 'Foreign category rejected');
check($import->lastBatch(2) === null, 'Failed import rolled back');
$import->deleteBatch(1, $batch);
check($import->lastBatch(1) === null && !$import->duplicate(1, $a, $rows[0]), 'Permanent deletion restores balances and duplicate availability');
check((int) $db->query('SELECT COUNT(*) FROM lotes_importacao WHERE id=' . $batch)->fetchColumn() === 0, 'Deleted batch is removed from database');
rejects(fn() => $import->deleteBatch(2, $batch), 'Foreign batch deletion rejected');
$archivedBatch = $import->import(1, $a, [$rows[0]], [0 => '1'], [0 => $expense['id']]);
$archivedTransaction = (int) $db->query('SELECT transacao_id FROM itens_importacao WHERE lote_id=' . $archivedBatch)->fetchColumn();
$db->exec("UPDATE transacoes SET status_antes_exclusao=status,status='cancelada',excluida_em=CURRENT_TIMESTAMP,versao=2 WHERE id IN (SELECT transacao_id FROM itens_importacao WHERE lote_id=$archivedBatch)");
$db->exec("UPDATE lotes_importacao SET desfeito_em=CURRENT_TIMESTAMP WHERE id=$archivedBatch");
check(count($import->batches(1)) === 1, 'Previously archived import remains available for permanent deletion');
$import->deleteBatch(1, $archivedBatch);
check((int) $db->query('SELECT COUNT(*) FROM transacoes WHERE id=' . $archivedTransaction)->fetchColumn() === 0 && $import->batches(1) === [], 'Previously archived import is permanently removed');
$draftRows = $import->parse('rascunho.csv', "Data;Descrição;Valor\n15/04/2025;Compra parcial;-8,00\n16/04/2025;Receita parcial;12,00\n");
$import->createDraft(1, $a, $draftRows);
$draft = $import->draft(1);
check($draft !== null && count($draft['rows']) === 2 && $import->draft(2) === null, 'Draft persists per user');
$import->saveDraftChoices(1, $draft['nonce'], [0 => '1'], [0 => $expense['id'], 1 => $income['id']]);
$draft = $import->draft(1);
check($draft['rows'][0]['selected'] && !$draft['rows'][1]['selected'] && (int)$draft['rows'][1]['category_id'] === (int)$income['id'], 'Draft keeps selection and categories');
$oldNonce = $draft['nonce'];
$partialBatch = $import->import(1, $a, $draft['rows'], [0 => '1'], [0 => $expense['id'], 1 => $income['id']], $oldNonce);
$remaining = $import->draft(1);
check($remaining !== null && count($remaining['rows']) === 1 && $remaining['rows'][0]['descricao'] === 'Receita parcial', 'Partial import keeps unselected row');
rejects(fn() => $import->saveDraftChoices(1, $oldNonce, [], []), 'Stale draft nonce rejected');
$import->removeDraftRow(1, $remaining['nonce'], 0);
check($import->draft(1) === null && $import->lastBatch(1)['id'] == $partialBatch, 'Removing last row clears draft only');
$import->createDraft(1, $a, $draftRows);
$draft = $import->draft(1);
rejects(fn() => $import->discardDraft(2, $draft['nonce']), 'Foreign draft discard rejected');
$import->discardDraft(1, $draft['nonce']);
check($import->draft(1) === null, 'Draft can be discarded');
$importCard = $cardService->save(1, null, ['nome' => 'Cartão para importação', 'limite' => '1000', 'dia_fechamento' => 20, 'dia_vencimento' => 5]);
$cardRows = $import->parse('cartao.csv', "Data;Descrição;Valor\n12/08/2025;Compra do cartão;-25,00\n");
$cardRows = $import->applyDefaults($cardRows, 'cartao', null, $importCard);
$beforeBalance = (int) $accounts->findById($a, 1)['saldo_atual_centavos'];
$cardBatch = $import->import(1, null, $cardRows, [0 => '1'], [0 => $expense['id']]);
$cardInvoice = $cards->invoices(1, $importCard)[0];
check((int) $cardInvoice['total'] === 2500 && (int) $accounts->findById($a, 1)['saldo_atual_centavos'] === $beforeBalance, 'Imported card purchase enters invoice without account debit');
check($import->duplicate(1, null, $cardRows[0]), 'Imported card purchase detected as duplicate');
$import->deleteBatch(1, $cardBatch);
check($cards->invoice(1, (int) $cardInvoice['id']) === null, 'Permanent deletion removes empty card invoice');
$mixed = $import->parse('misto.csv', "Data;Descrição;Valor\n13/08/2025;Compra mista;-10,00\n14/08/2025;Débito misto;-5,00\n");
$mixed[0] += ['destino_tipo' => 'cartao', 'cartao_id' => $importCard];
$mixed[1] += ['destino_tipo' => 'conta', 'conta_id' => $a, 'meio_pagamento' => 'debito'];
$mixedBatch = $import->import(1, $a, $mixed, [0 => '1', 1 => '1'], [0 => $expense['id'], 1 => $expense['id']]);
$mixedInvoice = $cards->invoices(1, $importCard)[0];
check((int) $mixedInvoice['total'] === 1000 && (int) $accounts->findById($a, 1)['saldo_atual_centavos'] === $beforeBalance - 500, 'Mixed import routes each row to card or account');
$cardService->close(1, (int) $mixedInvoice['id']);
rejects(fn() => $import->deleteBatch(1, $mixedBatch), 'Closed card invoice blocks batch deletion');
$cardRows[0]['cartao_id'] = $card;
rejects(fn() => $import->import(2, null, $cardRows, [0 => '1'], [0 => $foreignCategory['id']]), 'Foreign card rejected');
$cardRows[0]['cartao_id'] = $importCard;
$import->createDraft(1, null, $cardRows);
$draft = $import->draft(1);
$import->saveDraftChoices(1, $draft['nonce'], [0 => '1'], [0 => $expense['id']], [0 => 'cartao'], [], [0 => $importCard]);
check($import->draft(1)['rows'][0]['cartao_id'] === $importCard, 'Card selection persists in draft');
$import->discardDraft(1, $draft['nonce']);
echo "OK: importação CSV/OFX, conta/cartão, isolamento, duplicatas e exclusão permanente.\n";
