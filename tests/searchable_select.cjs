const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' });
  const page = await browser.newPage();
  await page.setContent(`<form id="form"><label for="cat">Categoria</label><select id="cat" name="categoria" required><option value="">Selecione</option><option value="1">Alimentação · Restaurante</option><option value="2">Saúde · Consulta</option><option value="3" disabled>Saúde · Exame</option></select><button>Salvar</button></form>`);
  await page.addScriptTag({ path: path.resolve(__dirname, '../public/js/searchable-select.js') });
  const input = page.locator('.searchable-select-input');
  await input.fill('sau');
  assert.deepEqual(await page.locator('[role=option]').allTextContents(), ['Saúde · Consulta']);
  await input.press('ArrowDown');
  await input.press('Enter');
  assert.equal(await page.locator('#cat').inputValue(), '2');
  assert.equal(await input.inputValue(), 'Saúde · Consulta');
  await input.fill('qualquer texto');
  assert.equal(await page.locator('#form').evaluate(form => form.checkValidity()), false);
  assert.equal(await page.locator('#cat').inputValue(), '2');
  await input.fill('alimentacao · restaurante');
  await input.press('Tab');
  assert.equal(await page.locator('#cat').inputValue(), '1');
  assert.deepEqual(await page.locator('#form').evaluate(form => [...new FormData(form).entries()]), [['categoria', '1']]);
  await page.locator('#cat').evaluate(select => { select.value = '2'; select.dispatchEvent(new Event('searchable:sync')); });
  assert.equal(await input.inputValue(), 'Saúde · Consulta');
  await page.locator('#cat').evaluate(select => { select.disabled = true; });
  await page.waitForFunction(() => document.querySelector('.searchable-select-input').disabled);
  await page.evaluate(() => { const s = document.createElement('select'); s.innerHTML = '<option>Nova opção</option>'; document.body.append(s); });
  await page.waitForFunction(() => document.querySelectorAll('.searchable-select-input').length === 2);
  const importPage = await browser.newPage();
  await importPage.setContent(`<form data-import-draft data-draft-save-url="/save"><div data-import-row data-import-income="0"><input type="checkbox" data-import-select><select data-import-target name="destino_tipo[0]"><option value="conta">Conta</option><option value="cartao">Compra no cartão</option></select><select data-import-account name="conta[0]"><option value="1">Conta A</option></select><select data-import-card name="cartao[0]"><option value="1">Cartão A</option></select><select data-import-method name="meio_pagamento[0]"><option value="pix">Pix</option></select></div><span data-draft-status></span><button type="button" data-select-all></button><button type="button" data-select-none></button></form>`);
  await importPage.addScriptTag({ path: path.resolve(__dirname, '../public/js/searchable-select.js') });
  await importPage.addScriptTag({ path: path.resolve(__dirname, '../public/js/import-draft.js') });
  await importPage.evaluate(() => document.dispatchEvent(new Event('DOMContentLoaded')));
  assert.equal(await importPage.locator('[data-import-card]').evaluate(s => s.closest('.searchable-select').classList.contains('d-none')), true);
  await importPage.locator('[data-import-target]').evaluate(s => { s.value = 'cartao'; s.dispatchEvent(new Event('change', { bubbles: true })); });
  assert.equal(await importPage.locator('[data-import-card]').evaluate(s => s.closest('.searchable-select').classList.contains('d-none')), false);
  assert.equal(await importPage.locator('[data-import-account]').evaluate(s => s.closest('.searchable-select').classList.contains('d-none')), true);
  await browser.close();
  console.log('OK: pesquisa, validação, teclado, sincronização e controles dinâmicos.');
})().catch(error => { console.error(error); process.exitCode = 1; });
